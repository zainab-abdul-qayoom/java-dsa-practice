package com.kunal;

public class PrettyPrinting {
    static void main(String[] args) {
        float a = 345.6778f;
        System.out.printf("Formatted number is: %.2f", a);
        System.out.println();

        System.out.printf("Pie %.3f", Math.PI);

        System.out.println();

        System.out.printf("My name is %s and I am %s", "Kunal", "Cool");

    }

}
